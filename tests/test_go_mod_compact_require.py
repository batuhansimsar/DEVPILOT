"""Regression tests for valid Go `require(` blocks without whitespace."""

import unittest

from devpilot.go_mod import parse_go_requirements


class CompactRequireBlockTests(unittest.TestCase):
    def test_compact_block_and_separate_requirement(self):
        content = (
            'module example.org/project\n'
            'require(\n'
            '  example.org/first v1.2.3\n'
            '  "example.net/second/v2" "v2.0.0" // indirect\n'
            ')\n'
            'require example.com/direct v3.0.0\n'
        )
        self.assertEqual(parse_go_requirements(content), [
            'example.com/direct', 'example.net/second/v2', 'example.org/first',
        ])

    def test_compact_block_with_comment_and_independent_blocks(self):
        content = (
            'require( // generated by go mod tidy\n'
            '  example.org/dependency v1.0.0\n'
            ')\n'
            'require (\n'
            '  example.com/other v1.0.0\n'
            ')\n'
        )
        self.assertEqual(parse_go_requirements(content), [
            'example.com/other', 'example.org/dependency',
        ])

    def test_invalid_inline_parentheses_do_not_open_block(self):
        content = (
            'require(example.org/not-accepted v1.2.3)\n'
            'example.com/not-in-a-block v1.0.0\n'
            'require example.org/valid v1.2.3\n'
        )
        self.assertEqual(parse_go_requirements(content), ['example.org/valid'])


if __name__ == '__main__':
    unittest.main()
