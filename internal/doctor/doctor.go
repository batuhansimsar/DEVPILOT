// Package doctor inspects a project without executing repository code.
package doctor

import (
    "encoding/json"
    "fmt"
    "io"
    "os"
    "os/exec"
    "path/filepath"
    "regexp"
    "sort"
    "strings"
)

type Finding struct {
    Level string `json:"level"`
    Code string `json:"code"`
    Message string `json:"message"`
    Remedy string `json:"remedy,omitempty"`
}
type Report struct {
    Path string `json:"path"`
    Languages []string `json:"languages"`
    Frameworks []string `json:"frameworks"`
    TestRunners []string `json:"test_runners"`
    Findings []Finding `json:"findings"`
}
func Root(path string) (string,error) {
    if path=="" {path="."}
    abs,err:=filepath.Abs(path);if err!=nil{return "",err}
    abs,err=filepath.EvalSymlinks(abs);if err!=nil{return "",fmt.Errorf("resolve workspace: %w",err)}
    stat,err:=os.Stat(abs);if err!=nil{return "",err}
    if !stat.IsDir(){return "",fmt.Errorf("workspace is not a directory: %s",abs)}
    return abs,nil
}
// Regular files only: repository-controlled symbolic links are ignored as
// manifest or environment-example inputs.
func regular(root,name string) bool {
    s,err:=os.Lstat(filepath.Join(root,name))
    return err==nil && s.Mode().IsRegular()
}
func readSmall(root,name string)([]byte,error){
    if !regular(root,name){return nil,fmt.Errorf("not a regular file: %s",name)}
    f,err:=os.Open(filepath.Join(root,name));if err!=nil{return nil,err}
    defer f.Close()
    data,err:=io.ReadAll(io.LimitReader(f,1024*1024+1));if err!=nil{return nil,err}
    if len(data)>1024*1024{return nil,fmt.Errorf("file exceeds 1 MiB: %s",name)}
    return data,nil
}
func Analyze(path string)(Report,error){
    root,err:=Root(path);if err!=nil{return Report{},err}
    r:=Report{Path:root,Languages:[]string{},Frameworks:[]string{},TestRunners:[]string{},Findings:[]Finding{}}
    add:=func(level,code,message,remedy string){r.Findings=append(r.Findings,Finding{level,code,message,remedy})}
    tooling:=map[string]string{}
    if regular(root,"go.mod"){
        r.Languages=append(r.Languages,"Go");r.TestRunners=append(r.TestRunners,"go")
        tooling["go"]="Install Go to build and test this module: https://go.dev/dl/"
    }
    if regular(root,"package.json"){
        r.Languages=append(r.Languages,"JavaScript/TypeScript")
        locks:=[]string{}
        for _,name:=range []string{"package-lock.json","pnpm-lock.yaml","yarn.lock","bun.lock","bun.lockb"}{
            if regular(root,name){locks=append(locks,name)}
        }
        if len(locks)>1{add("warning","multiple-lockfiles","Multiple JavaScript lockfiles: "+strings.Join(locks,", "),"Keep the lockfile for the package manager actually used by the project.")}
        manager:="npm"
        switch{
        case contains(locks,"pnpm-lock.yaml"):manager="pnpm"
        case contains(locks,"yarn.lock"):manager="yarn"
        case contains(locks,"bun.lock")||contains(locks,"bun.lockb"):manager="bun"
        }
        tooling[manager]="Install "+manager+" to manage project dependencies."
        data,readErr:=readSmall(root,"package.json")
        if readErr!=nil{add("warning","manifest-unreadable","Cannot read package.json: "+readErr.Error(),"Use a regular, valid package.json smaller than 1 MiB.")}else{
            var manifest struct{
                Scripts map[string]string `json:"scripts"`
                Dependencies map[string]json.RawMessage `json:"dependencies"`
                DevDependencies map[string]json.RawMessage `json:"devDependencies"`
            }
            if err:=json.Unmarshal(data,&manifest);err!=nil{
                add("warning","manifest-invalid","Cannot parse package.json: "+err.Error(),"Fix JSON syntax in package.json.")
            }else{
                if _,ok:=manifest.Scripts["test"];ok{r.TestRunners=append(r.TestRunners,manager)}
                for _,fw:=range []string{"react","next","vue","svelte","angular","express","vite"}{
                    if _,ok:=manifest.Dependencies[fw];ok{r.Frameworks=append(r.Frameworks,fw)}else if _,ok:=manifest.DevDependencies[fw];ok{r.Frameworks=append(r.Frameworks,fw)}
                }
                if _,ok:=manifest.Scripts["test"];!ok{add("info","no-npm-test","package.json has no test script.","Add a test script when automated tests are available.")}
            }
        }
        if len(locks)==0{add("info","lockfile-missing","No JavaScript package lockfile was detected.","Commit the lockfile generated by your chosen package manager for reproducible installs.")}
    }
    if regular(root,"pyproject.toml")||regular(root,"requirements.txt"){
        r.Languages=append(r.Languages,"Python");tooling["python"]="Install Python 3 to run Python tooling."
        if regular(root,"pytest.ini")||regular(root,"conftest.py"){r.TestRunners=append(r.TestRunners,"pytest")}
    }
    if regular(root,"Cargo.toml"){
        r.Languages=append(r.Languages,"Rust");r.TestRunners=append(r.TestRunners,"cargo")
        tooling["cargo"]="Install Rust and Cargo using rustup."
    }
    projects,_:=filepath.Glob(filepath.Join(root,"*.csproj"))
    solutions,_:=filepath.Glob(filepath.Join(root,"*.sln"))
    if len(projects)+len(solutions)>0{
        r.Languages=append(r.Languages,"C#");r.TestRunners=append(r.TestRunners,"dotnet")
        tooling["dotnet"]="Install the .NET SDK from https://dotnet.microsoft.com/download."
    }
    if regular(root,".git")||isDir(root,".git"){add("info","git-detected","Git repository metadata is present.","")}else{add("info","git-absent","No .git metadata was detected at the workspace root.","Run git init if version control is desired.")}
    tools:=make([]string,0,len(tooling))
    for name:=range tooling{tools=append(tools,name)};sort.Strings(tools)
    for _,name:=range tools{
        if _,err:=exec.LookPath(name);err!=nil{add("warning","tool-missing","Required tool not found in PATH: "+name,tooling[name])}else{add("info","tool-found","Tool available in PATH: "+name,"")}
    }
    if regular(root,".env.example"){
        data,err:=readSmall(root,".env.example")
        if err!=nil{add("warning","env-example-unreadable",err.Error(),"Make .env.example a regular file smaller than 1 MiB.")}else{
            pattern:=regexp.MustCompile(`(?m)^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=`)
            seen:=map[string]bool{}
            for _,m:=range pattern.FindAllSubmatch(data,-1){
                key:=string(m[1])
                if !seen[key]{seen[key]=true;if _,ok:=os.LookupEnv(key);!ok{
                    add("info","env-not-exported",key+" is listed in .env.example but not exported in the current process.","Set it before running the app if the application requires it; a local .env file may also supply it.")
                }}
            }
        }
    }
    if len(r.Languages)==0{add("warning","project-unrecognized","No supported root-level project manifest was found.","Run DevPilot in a Go, Node.js, Python, Rust, or .NET project root.")}
    sort.Strings(r.Languages);sort.Strings(r.Frameworks);sort.Strings(r.TestRunners)
    return r,nil
}
func contains(items []string,value string)bool{for _,item:=range items{if item==value{return true}};return false}
func isDir(root,name string)bool{s,err:=os.Lstat(filepath.Join(root,name));return err==nil&&s.IsDir()}
// TestCommand selects a known tool without invoking a shell. Repository test
// scripts remain untrusted and require an explicit CLI trust flag.
func TestCommand(r Report,requested string)(string,[]string,error){
    if requested==""{
        if len(r.TestRunners)==0{return "",nil,fmt.Errorf("no supported test runner detected")}
        if len(r.TestRunners)>1{return "",nil,fmt.Errorf("multiple test runners detected (%s); select one with --runner",strings.Join(r.TestRunners,", "))}
        requested=r.TestRunners[0]
    }
    if !contains(r.TestRunners,requested){return "",nil,fmt.Errorf("test runner %q was not discovered in this project",requested)}
    switch requested{
    case "go":return "go",[]string{"test","./..."},nil
    case "npm":return "npm",[]string{"test"},nil
    case "pnpm":return "pnpm",[]string{"test"},nil
    case "yarn":return "yarn",[]string{"test"},nil
    case "bun":return "bun",[]string{"test"},nil
    case "cargo":return "cargo",[]string{"test"},nil
    case "pytest":return "python",[]string{"-m","pytest"},nil
    case "dotnet":return "dotnet",[]string{"test"},nil
    }
    return "",nil,fmt.Errorf("unsupported runner: %s",requested)
}
